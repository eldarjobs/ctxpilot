'use strict';
const fs = require('fs');
const path = require('path');
const { getPaths, discoverMcp, discoverRules, tryParseJson } = require('./discovery');
const { listFixes } = require('./handoff');
const { classifySecret, suggestReplacement } = require('./redact');

const SYNC_HEADER = '<!-- Generated by ctxpilot sync — edit AGENTS.md or .agents/rules/ -->';

function stripFrontmatter(text) {
    return String(text || '').replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '').trim();
}

function sanitizeMcpServersForExport(servers) {
    const out = {};
    for (const srv of servers) {
        if (srv.client && srv.client !== 'antigravity') continue;
        if (srv.parked || srv.disabledInConfig || srv.transport === 'plugin') continue;
        const clone = JSON.parse(JSON.stringify(srv.def || {}));
        for (const loc of ['headers', 'env']) {
            if (!clone[loc] || typeof clone[loc] !== 'object') continue;
            for (const [k, v] of Object.entries(clone[loc])) {
                const kind = classifySecret(k, v);
                if (kind) {
                    const sug = suggestReplacement(srv.id, loc, k, v, kind);
                    clone[loc][k] = /^Bearer\s+/i.test(String(v)) ? `Bearer \${${sug.envVar}}` : `\${${sug.envVar}}`;
                }
            }
        }
        out[srv.id] = clone;
    }
    return out;
}

/**
 * Compiles canonical AGENTS.md + .agents/rules + workspace FIXES into target AI coding clients.
 */
function syncAgents(opts = {}) {
    const paths = getPaths(opts);
    const ws = paths.workspaceDir;
    const rules = discoverRules(ws);
    const fixes = listFixes(opts).slice(0, 10);

    const rootFile = ['AGENTS.md', 'GEMINI.md', 'CLAUDE.md'].find(f => fs.existsSync(path.join(ws, f))) || null;
    const rootText = rootFile ? fs.readFileSync(path.join(ws, rootFile), 'utf8').trim() : '';
    const projectRules = rules.items.filter(r => r.source === '.agents/rules' && r.name !== '00-active-mcps.md' && r.trigger !== 'disabled');

    if (!rootText && projectRules.length === 0 && fixes.length === 0 && !opts.mcp) {
        return { action: 'sync', workspace: ws, dryRun: Boolean(opts.dryRun), written: [], reason: 'No canonical AGENTS.md, .agents/rules, or fixes found.' };
    }

    const sections = [SYNC_HEADER];
    if (rootText) sections.push(rootText);
    for (const r of projectRules) {
        const body = stripFrontmatter(r.text);
        if (body) sections.push(`## Rule: ${r.name.replace(/\.md$/, '')}\n\n${body}`);
    }
    if (fixes.length) {
        sections.push('## Workspace Lessons & Fixes\n\n' + fixes.map(f => `- ${f.title}${f.detail ? `: ${f.detail}` : ''}`).join('\n'));
    }
    const compiled = sections.join('\n\n') + '\n';

    const requested = Array.isArray(opts.targets) && opts.targets.length
        ? opts.targets.map(t => t.toLowerCase())
        : ['claude', 'codex', 'cursor', 'windsurf'];

    const files = [];
    const addTarget = (target, relPath, content) => {
        const full = path.join(ws, relPath);
        const existing = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
        if (existing === content) {
            files.push({ target, path: full, status: 'unchanged' });
            return;
        }
        if (!opts.dryRun) {
            fs.mkdirSync(path.dirname(full), { recursive: true });
            fs.writeFileSync(full, content, 'utf8');
        }
        files.push({ target, path: full, status: opts.dryRun ? 'would-write' : (existing === null ? 'created' : 'updated') });
    };

    if (requested.includes('claude') && rootFile !== 'CLAUDE.md') addTarget('claude', 'CLAUDE.md', compiled);
    if (requested.includes('codex') && rootFile !== 'AGENTS.md') addTarget('codex', 'AGENTS.md', compiled);
    if (requested.includes('cursor')) {
        const mdc = ['---', 'description: Synced project rules from ctxpilot', 'alwaysApply: true', '---', '', compiled].join('\n');
        addTarget('cursor', path.join('.cursor', 'rules', 'ctxpilot-synced.mdc'), mdc);
    }
    if (requested.includes('windsurf')) addTarget('windsurf', '.windsurfrules', compiled);

    if (opts.mcp) {
        const mcp = discoverMcp(paths);
        const sanitized = sanitizeMcpServersForExport(mcp.servers);
        const mcpJson = JSON.stringify({ mcpServers: sanitized }, null, 2) + '\n';
        if (requested.includes('claude')) addTarget('claude-mcp', '.mcp.json', mcpJson);
        if (requested.includes('cursor')) {
            const curPath = path.join(ws, '.cursor', 'mcp.json');
            const curExisting = tryParseJson(curPath).data || {};
            const merged = JSON.stringify({ ...curExisting, mcpServers: { ...(curExisting.mcpServers || {}), ...sanitized } }, null, 2) + '\n';
            addTarget('cursor-mcp', path.join('.cursor', 'mcp.json'), merged);
        }
    }

    return {
        action: 'sync',
        workspace: ws,
        source: rootFile || '.agents/rules',
        dryRun: Boolean(opts.dryRun),
        written: files,
    };
}

module.exports = { syncAgents, sanitizeMcpServersForExport };
